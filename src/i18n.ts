export type Strings = typeof en;

function enUnit(n: number, unit: Unit): string {
  const word = { DAY: 'day', WEEK: 'week', MONTH: 'month', YEAR: 'year' }[unit];
  return n === 1 ? word : `${word}s`;
}

// ---------- German (du, as iOS itself speaks German) ----------

function deUnit(n: number, unit: Unit): string {
  const [one, many] = { DAY: ['Tag', 'Tage'], WEEK: ['Woche', 'Wochen'], MONTH: ['Monat', 'Monate'], YEAR: ['Jahr', 'Jahre'] }[unit];
  return n === 1 ? one : many;
}

