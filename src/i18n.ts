/**
 * The app's words in English, German, French, Spanish and Italian, as pure
 * TypeScript (no runtime imports), so `npm test` can check every language.
 *
 * English is the default and the fallback: a phone set to any other
 * language sees English. App.tsx calls `setLocale` once at launch with the
 * device's language (expo-localization); `t()` then returns that language's
 * strings. Dates and numbers are formatted with the device's own locale.
 *
 * Every language has exactly the keys of `en` (TypeScript checks it).
 * Strings with numbers or prices are functions, so each language can put
 * the words in its own order and pick singular or plural. Prices and
 * periods of the plans always arrive as RevenueCat price strings; only the
 * words around them are here.
 */

export type Lang = 'en' | 'de' | 'fr' | 'es' | 'it';
export const LANGS: Lang[] = ['en', 'de', 'fr', 'es', 'it'];
/** A store period unit, as RevenueCat names it. */
export type Unit = 'DAY' | 'WEEK' | 'MONTH' | 'YEAR';

let current: Lang = 'en';
let deviceTag = 'en-US';

/** Sets the language from the device's first preferred language. Anything but de, fr, es or it is English. */
export function setLocale(languageTag?: string | null, languageCode?: string | null): void {
  const code = (languageCode || languageTag || 'en').toLowerCase().split(/[-_]/)[0];
  current = (LANGS as string[]).includes(code) ? (code as Lang) : 'en';
  deviceTag = languageTag || 'en-US';
}

export function lang(): Lang {
  return current;
}

/** The device's locale tag, for dates and numbers ("de-DE", "fr-CH", "en-US"). */
export function locale(): string {
  return deviceTag;
}

/** The strings in the app's language. */
export function t(): Strings {
  return DICTS[current];
}

/** The strings in a given language (for checks). */
export function strings(l: Lang): Strings {
  return DICTS[l];
}

// ---------- numbers and dates ----------

function safe<T>(f: (tag: string) => T, fallback: () => T): T {
  try {
    return f(deviceTag);
  } catch {
    return fallback();
  }
}

/** 1,204 / 1.204 / 1 204, as the device writes numbers. */
export function num(n: number): string {
  return safe(
    (tag) => n.toLocaleString(tag),
    () => String(n)
  );
}

/** 2:41 pm / 14:41, as the device writes times. English keeps its lowercase am and pm. */
export function timeOf(d: Date): string {
  const s = safe(
    (tag) => d.toLocaleTimeString(tag, { hour: 'numeric', minute: '2-digit' }),
    () => `${d.getHours()}:${String(d.getMinutes()).padStart(2, '0')}`
  );
  return current === 'en' ? s.toLowerCase() : s;
}

/** Oct 22 / 22. Okt. / 22 oct., with the year when it is not this year. */
export function shortDate(d: Date, withYear: boolean): string {
  return safe(
    (tag) => d.toLocaleDateString(tag, { month: 'short', day: 'numeric', ...(withYear ? { year: 'numeric' } : {}) }),
    () => d.toDateString()
  );
}

/** November 17, 2026 / 17. November 2026, for the PDF's header. */
export function longDate(d: Date): string {
  return safe(
    (tag) => d.toLocaleDateString(tag, { year: 'numeric', month: 'long', day: 'numeric' }),
    () => d.toDateString()
  );
}

/** "Today, 2:41 pm", "Yesterday, 9:05 am", or the date. */
export function whenLabel(ms: number, now = Date.now()): string {
  const d = new Date(ms);
  const n = new Date(now);
  const s = t();
  if (d.toDateString() === n.toDateString()) return s.today(timeOf(d));
  const y = new Date(now - 86_400_000);
  if (d.toDateString() === y.toDateString()) return s.yesterday(timeOf(d));
  return shortDate(d, d.getFullYear() !== n.getFullYear());
}

